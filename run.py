#!/usr/bin/env python3
"""Run the questionnaire checks and write the contractor review table.

    python run.py

Reads  data/synthetic_responses.csv   (synthetic records, see the data notice)
Writes out/review_table.csv           one row per interview record x question
       out/review_table.md            the same table, readable
       out/summary.md                 counts by rule, for the covering note

Standard library only. No arguments, no configuration, no network.
"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from checks.rules import run_all  # noqa: E402

BASE = os.path.dirname(os.path.abspath(__file__))
IN_CSV = os.path.join(BASE, "data", "synthetic_responses.csv")
OUT_DIR = os.path.join(BASE, "out")

COLUMNS = ["record_id", "question", "variable", "value", "rule_id",
           "rule_source", "severity", "message", "source_text"]


def read_records(path):
    records = []
    with open(path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            rec = {}
            for k, v in row.items():
                if k == "id":
                    rec[k] = v
                elif v == "":
                    rec[k] = ""
                else:
                    try:
                        rec[k] = int(v)
                    except ValueError:
                        rec[k] = v
            records.append(rec)
    return records


def write_csv(findings, path):
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(COLUMNS)
        for x in findings:
            w.writerow([x.record_id, x.question, x.variable, x.value, x.rule_id,
                        x.rule_source, x.severity, x.message, x.source_text])


def write_markdown(findings, records, path):
    by_record = {}
    for x in findings:
        by_record.setdefault(x.record_id, []).append(x)

    lines = [
        "# Review table — synthetic Enterprise Surveys records",
        "",
        "Generated by `python run.py`. **Synthetic data. Not World Bank survey data.**",
        "",
        "Comments organised by interview and by question, the form the Enterprise Surveys",
        "*Manual and Guide* (§4.4.3) describes for the output a vendor uses to manage",
        "call-backs to respondents.",
        "",
        f"{len(records)} records checked · {len(by_record)} with findings · "
        f"{len(findings)} findings in total.",
        "",
    ]
    for rec in records:
        rid = rec["id"]
        items = by_record.get(rid)
        if not items:
            lines += [f"## {rid}", "", "No findings.", ""]
            continue
        errors = sum(1 for i in items if i.severity == "error")
        reviews = len(items) - errors
        lines += [
            f"## {rid}",
            "",
            f"{errors} to correct · {reviews} to confirm",
            "",
            "| Question | Variable | Value | Rule | Basis | Action | What to check |",
            "|---|---|---|---|---|---|---|",
        ]
        for i in items:
            action = "correct" if i.severity == "error" else "confirm"
            basis = "questionnaire" if i.rule_source == "questionnaire" else "reviewer"
            lines.append(
                f"| {i.question} | `{i.variable}` | {i.value} | {i.rule_id} | "
                f"{basis} | {action} | {i.message} |")
        lines += ["", "<details><summary>Rule wording</summary>", ""]
        seen = set()
        for i in items:
            if i.rule_id in seen:
                continue
            seen.add(i.rule_id)
            lines.append(f"- **{i.rule_id}** — {i.source_text}")
        lines += ["", "</details>", ""]

    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def write_summary(findings, records, path):
    by_rule = {}
    for x in findings:
        key = (x.rule_id, x.rule_source, x.severity)
        by_rule.setdefault(key, []).append(x.record_id)

    lines = [
        "# Summary by rule",
        "",
        f"{len(records)} synthetic records checked, {len(findings)} findings.",
        "",
        "| Rule | Basis | Action | Records | Which |",
        "|---|---|---|---|---|",
    ]
    for (rule_id, source, severity) in sorted(by_rule):
        ids = sorted(set(by_rule[(rule_id, source, severity)]))
        basis = "questionnaire" if source == "questionnaire" else "reviewer"
        action = "correct" if severity == "error" else "confirm"
        lines.append(f"| {rule_id} | {basis} | {action} | {len(ids)} | "
                     f"{', '.join(ids)} |")
    lines += [
        "",
        "`questionnaire` means the rule is printed on the public core questionnaire.",
        "`reviewer` means it is a consistency or plausibility check I defined; those are",
        "raised for confirmation, never corrected automatically.",
        "",
    ]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    records = read_records(IN_CSV)
    findings = run_all(records)

    write_csv(findings, os.path.join(OUT_DIR, "review_table.csv"))
    write_markdown(findings, records, os.path.join(OUT_DIR, "review_table.md"))
    write_summary(findings, records, os.path.join(OUT_DIR, "summary.md"))

    errors = sum(1 for f in findings if f.severity == "error")
    print(f"{len(records)} records checked")
    print(f"{len(findings)} findings  ({errors} to correct, "
          f"{len(findings) - errors} to confirm)")
    print("wrote out/review_table.csv, out/review_table.md, out/summary.md")


if __name__ == "__main__":
    main()
